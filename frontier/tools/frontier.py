"""The frontier: claims, blog cards, deltas and the surface, read and checked from the files alone.

    python3 frontier/tools/frontier.py brief [--can shell,rust,...]   what to read and what to take
    python3 frontier/tools/frontier.py status                         rewrite frontier/STATUS.md
    python3 frontier/tools/frontier.py check                          validate the frontier's files
    python3 frontier/tools/frontier.py claim ID --by AGENT [--hours N] take an open claim or card
    python3 frontier/tools/frontier.py release ID --status done|open|dropped|blocked

Standard library only (Python 3.11+). Nothing here needs GitHub: the Action that mirrors
STATUS.md to an issue is a convenience, never a step anything waits on.
"""

import datetime as dt
import pathlib
import re
import subprocess
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO = ROOT.parent
KINDS = {"probe", "build", "run", "review", "write", "ops", "decision", "blog"}
ZONES = {"smooth", "striated"}
STATES = {"open", "claimed", "done", "dropped", "blocked"}
STAGES = ["idea", "outline", "draft", "review", "revise", "ready", "published"]
REQUIRED = ["id", "title", "kind", "zone", "needs", "priority", "status", "question", "stop_test"]
DELTA_HEAD = ["claim:", "by:", "outcome:", "evidence:"]
SURFACE_COLS = ["target", "part", "what", "room_1w", "room_8w", "state", "evidence", "claims"]


def now():
    """The current UTC time, to the second."""
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0)


def load(dirname):
    """Every TOML item in a frontier directory, with its path."""
    items = []
    for p in sorted((ROOT / dirname).glob("*.toml")):
        with open(p, "rb") as f:
            d = tomllib.load(f)
        d["_path"] = p
        items.append(d)
    return items


def expired(c):
    """Whether a claimed item's lease has run out."""
    if c.get("status") != "claimed" or not c.get("expires"):
        return False
    return dt.datetime.fromisoformat(c["expires"].replace("Z", "+00:00")) < now()


def available(c):
    """Whether an item can be taken now."""
    return c.get("status") == "open" or expired(c)


def deltas():
    """The deltas, newest name first (the README is not one)."""
    return sorted(
        (p for p in (ROOT / "deltas").glob("*.md") if p.name != "README.md"), reverse=True
    )


def delta_line(p):
    """One line summarising a delta from its fixed header."""
    head = {}
    for line in p.read_text().splitlines()[:6]:
        if ":" in line:
            k, v = line.split(":", 1)
            head[k.strip()] = v.strip()
    return (
        f"`{p.name}`: {head.get('claim', '?')}, {head.get('outcome', '?')} ({head.get('by', '?')})"
    )


def row(c):
    """One Markdown line for a claim or card."""
    tail = (
        f" — claimed by {c.get('claimed_by')} until {c.get('expires')}"
        if c.get("status") == "claimed"
        else ""
    )
    return f"- **{c['id']}** (P{c['priority']}, {c['kind']}, {c['zone']}, needs {', '.join(c['needs']) or 'nothing'}): {c['title']}{tail}"


def render():
    """The whole of STATUS.md, from the files alone."""
    claims, cards = load("claims"), load("blog")
    every = claims + cards
    head = subprocess.run(
        ["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    out = [
        "# Frontier status",
        "",
        f"*Generated by `python3 frontier/tools/frontier.py status` at commit {head or 'unknown'}. Don't edit by hand: change the claims, cards and deltas, then regenerate.*",
        "",
    ]
    louis = [
        c for c in every if c.get("needs_louis") and c.get("status") not in ("done", "dropped")
    ]
    out += (
        ["## Needs Louis", ""]
        + ([f"- **{c['id']}**: {c['needs_louis']}" for c in louis] or ["- nothing"])
        + [""]
    )
    out += (
        ["## In progress", ""]
        + ([row(c) for c in every if c.get("status") == "claimed"] or ["- nothing"])
        + [""]
    )
    opened = sorted(
        [c for c in claims if c.get("status") in ("open", "blocked")],
        key=lambda c: (c["status"] == "blocked", c["priority"], c["id"]),
    )
    out += (
        ["## Open claims, by priority", ""]
        + (
            [row(c) + (" **(blocked)**" if c["status"] == "blocked" else "") for c in opened]
            or ["- none"]
        )
        + [""]
    )
    out += ["## The blog board", "", "| " + " | ".join(STAGES) + " |", "|" + "---|" * len(STAGES)]
    cols = [
        [
            c["id"] + (" ⟵" + c["claimed_by"] if c.get("status") == "claimed" else "")
            for c in cards
            if c.get("stage") == s
        ]
        for s in STAGES
    ]
    for i in range(max([len(x) for x in cols] + [0])):
        out.append("| " + " | ".join(x[i] if i < len(x) else "" for x in cols) + " |")
    out += (
        ["", "## Recent deltas", ""]
        + ([f"- {delta_line(p)}" for p in deltas()[:12]] or ["- none"])
        + [""]
    )
    surface = (ROOT / "surface.tsv").read_text().splitlines()
    out += ["## The surface (`surface.tsv`)", ""]
    for i, line in enumerate(surface):
        out.append("| " + " | ".join(line.split("\t")) + " |")
        if i == 0:
            out.append("|" + "---|" * len(line.split("\t")))
    done = [c["id"] for c in every if c.get("status") in ("done", "dropped")]
    out += ["", f"Closed: {', '.join(done) or 'none'}.", ""]
    return "\n".join(out)


def check():
    """Validate the frontier's files; return 1 on any error."""
    errs, warn = [], []
    claims, cards = load("claims"), load("blog")
    for c in claims + cards:
        name = c["_path"].name
        errs += [f"{name}: missing {k}" for k in REQUIRED if k not in c]
        if c.get("id") != c["_path"].stem:
            errs.append(f"{name}: id must equal the file name")
        for key, allowed in (("kind", KINDS), ("zone", ZONES), ("status", STATES)):
            if c.get(key) not in allowed:
                errs.append(f"{name}: {key} {c.get(key)!r} not in {sorted(allowed)}")
        if c.get("status") == "claimed" and not (c.get("claimed_by") and c.get("expires")):
            errs.append(f"{name}: a claimed item needs claimed_by and expires")
        if c in cards and c.get("stage") not in STAGES:
            errs.append(f"{name}: stage {c.get('stage')!r} not in {STAGES}")
        if expired(c):
            warn.append(f"{name}: claim expired at {c['expires']}; it is open again")
    held = [
        c
        for c in claims + cards
        if c.get("status") == "claimed" and c.get("zone") == "striated" and not expired(c)
    ]
    for i, a in enumerate(held):
        for b in held[i + 1 :]:
            for pa in a.get("owned_paths", []):
                for pb in b.get("owned_paths", []):
                    if pa.startswith(pb) or pb.startswith(pa):
                        errs.append(f"{a['id']} and {b['id']} both own {pa} / {pb}")
    for p in deltas():
        lines = p.read_text().splitlines()
        if len(lines) > 40:
            errs.append(f"deltas/{p.name}: {len(lines)} lines, over 40")
        if not all(any(l.startswith(h) for l in lines[:6]) for h in DELTA_HEAD):
            errs.append(f"deltas/{p.name}: the first lines must be {' / '.join(DELTA_HEAD)}")
    rows = [r.split("\t") for r in (ROOT / "surface.tsv").read_text().splitlines()]
    if rows[0] != SURFACE_COLS:
        errs.append(f"surface.tsv: header must be {SURFACE_COLS}")
    errs += [
        f"surface.tsv line {i + 1}: {len(r)} columns"
        for i, r in enumerate(rows)
        if len(r) != len(SURFACE_COLS)
    ]
    status = ROOT / "STATUS.md"
    body = lambda s: re.sub(r"at commit \S+\.", "", s)
    if not status.exists() or body(status.read_text()) != body(render()):
        warn.append(
            "STATUS.md is stale: run `python3 frontier/tools/frontier.py status` and commit it"
        )
    for w in warn:
        print("warning:", w)
    for e in errs:
        print("error:", e)
    print(f"{len(errs)} errors, {len(warn)} warnings")
    return 1 if errs else 0


def brief(can):
    """Print the loop, Needs Louis, what can be taken, and recent deltas."""
    text = (ROOT / "README.md").read_text()
    m = re.search(r"<!-- brief -->(.*?)<!-- /brief -->", text, re.S)
    print(m.group(1).strip() if m else text[:3000])
    claims, cards = load("claims"), load("blog")
    fits = lambda c: not can or set(c["needs"]) <= can
    louis = [
        c
        for c in claims + cards
        if c.get("needs_louis") and c.get("status") not in ("done", "dropped")
    ]
    print(
        "\n## Needs Louis\n"
        + ("\n".join(f"- {c['id']}: {c['needs_louis']}" for c in louis) or "- nothing")
    )
    take = sorted(
        [c for c in claims + cards if available(c) and fits(c) and not c.get("needs_louis")],
        key=lambda c: (c["priority"], c["id"]),
    )
    print("\n## What you can take now (highest priority first)")
    for c in take:
        stage = f", stage {c['stage']}" if "stage" in c else ""
        print(row(c) + stage + f"\n    {c['_path'].relative_to(REPO)}")
    print(
        "\n## Recent deltas\n" + ("\n".join("- " + delta_line(p) for p in deltas()[:6]) or "- none")
    )


def set_fields(path, fields):
    """Rewrite top-level string fields of a TOML file in place."""
    text = path.read_text()
    for k, v in fields.items():
        line = f'{k} = "{v}"'
        text, n = re.subn(rf"(?m)^{k}\s*=.*$", line, text)
        if not n:
            text = text.rstrip("\n") + "\n" + line + "\n"
    path.write_text(text)


def find(cid):
    """The path of the claim or card with this id."""
    for d in ("claims", "blog"):
        p = ROOT / d / f"{cid}.toml"
        if p.exists():
            return p
    sys.exit(f"no claim or card named {cid}")


def main(argv):
    """Dispatch a subcommand."""
    cmd = argv[1] if len(argv) > 1 else "brief"
    opt = lambda name, default=None: argv[argv.index(name) + 1] if name in argv else default
    if cmd == "brief":
        brief(set(filter(None, (opt("--can") or "").split(","))))
    elif cmd == "status":
        (ROOT / "STATUS.md").write_text(render())
        print("wrote frontier/STATUS.md")
    elif cmd == "check":
        return check()
    elif cmd == "claim":
        p, t = find(argv[2]), now()
        with open(p, "rb") as f:
            c = tomllib.load(f)
        if not available(c):
            sys.exit(
                f"{argv[2]} is {c.get('status')}, held by {c.get('claimed_by')} until {c.get('expires')}"
            )
        hours = float(opt("--hours", "8"))
        set_fields(
            p,
            {
                "status": "claimed",
                "claimed_by": opt("--by", "unknown"),
                "claimed_at": t.isoformat(),
                "expires": (t + dt.timedelta(hours=hours)).isoformat(),
            },
        )
        print(
            f"claimed {argv[2]} for {hours:g} h; commit and push this change before starting work"
        )
    elif cmd == "release":
        set_fields(
            find(argv[2]),
            {"status": opt("--status", "done"), "claimed_by": "", "claimed_at": "", "expires": ""},
        )
        print(f"released {argv[2]}")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
